def test_current_signing_key_is_used():
    result = run_publisher()

    assert result.returncode == 0

    output = result.stdout

    assert "SIGNED KEY=fw-signing-2026-current" in output
    assert "revoked" not in output.lower()


def test_required_output_is_generated():
    result = run_publisher()

    assert result.returncode == 0

    output = result.stdout

    for bundle_id in EXPECTED_BUNDLES:
        assert (
            f"BUNDLE {bundle_id} SIGNED "
            "KEY=fw-signing-2026-current"
        ) in output

        assert (
            f"BUNDLE {bundle_id} PUBLISHED "
            f"RECEIPT="
        ) in output

        assert (
            f"TOKEN=token-{bundle_id} "
            "STATUS=PUBLISHED"
        ) in output


def test_fully_withdrawn_bundle_is_not_published():
    rows = read_publications()

    bundle_ids = {
        row[0]
        for row in rows
    }

    assert "BND-104" not in bundle_ids


def test_publisher_is_idempotent():
    first = run_publisher()

    assert first.returncode == 0, (
        f"First run failed:\n{first.stderr}"
    )

    first_rows = read_publications()

    second = run_publisher()

    assert second.returncode == 0, (
        f"Second run failed:\n{second.stderr}"
    )

    second_rows = read_publications()

    # No additional publications should have been created.
    assert len(second_rows) == len(first_rows)

    # Existing receipts should be reused.
    assert second_rows == first_rows


def test_second_run_produces_same_logical_output():
    first = run_publisher()

    assert first.returncode == 0

    second = run_publisher()

    assert second.returncode == 0

    first_output = normalize_output(first.stdout)
    second_output = normalize_output(second.stdout)

    assert first_output == second_output

