import os
import re
import subprocess
from pathlib import Path

import duckdb
import pytest


APP_ROOT = Path("/app")
PUBLISHER = APP_ROOT / "publisher" / "release-publisher.mjs"
DATABASE = APP_ROOT / "releases.duckdb"

EXPECTED_BUNDLES = {
    "BND-101": {
        "artifact_count": 9,
        "total_bytes": 1201575,
    },
    "BND-102": {
        "artifact_count": 10,
        "total_bytes": 2188075,
    },
    "BND-103": {
        "artifact_count": 8,
        "total_bytes": 2079625,
    },
}


def run_publisher():
    result = subprocess.run(
        ["node", str(PUBLISHER)],
        cwd=APP_ROOT,
        capture_output=True,
        text=True,
        timeout=120,
    )

    return result


def read_publications():
    connection = duckdb.connect(str(DATABASE))

    try:
        return connection.execute(
            """
            SELECT
                bundle_id,
                request_token,
                publication_id,
                status
            FROM publications
            ORDER BY bundle_id
            """
        ).fetchall()
    finally:
        connection.close()


def normalize_output(output):
    """
    Publication IDs are generated by the gateway, so replace them
    before comparing output from two runs.
    """
    return re.sub(
        r"RECEIPT=pub_[A-Za-z0-9]+",
        "RECEIPT=<publication-id>",
        output,
    )


def test_publisher_runs_successfully():
    result = run_publisher()

    assert result.returncode == 0, (
        "Publisher failed.\n"
        f"stdout:\n{result.stdout}\n"
        f"stderr:\n{result.stderr}"
    )


def test_expected_bundles_are_published():
    rows = read_publications()

    published_bundles = {
        row[0]
        for row in rows
    }

    assert published_bundles == {
        "BND-101",
        "BND-102",
        "BND-103",
    }

    assert "BND-104" not in published_bundles


def test_publication_count_is_correct():
    rows = read_publications()

    assert len(rows) == 3


def test_publication_receipts_are_persisted():
    rows = read_publications()

    for bundle_id, token, publication_id, status in rows:
        assert token == f"token-{bundle_id}"
        assert publication_id.startswith("pub_")
        assert status == "PUBLISHED"


